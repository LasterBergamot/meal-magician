-- Phase 5 (#124, PLAN.md D27): ratings. One member rates one planned slot with a thumb (required),
-- stars (optional) and a short comment (optional). Portable SQL: it runs unchanged on H2
-- (PostgreSQL mode) and on Postgres. Expand-only: a new table, so the previous release keeps
-- working while this one rolls out (D13).
CREATE TABLE rating (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT      NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    -- The rated slot. Deliberately NO foreign key to meal_slot (D27): a rating outlives its slot, so
    -- replacing a day or week (D26) or removing a slot never deletes what people said about the
    -- meal. The slot's date, type and meal are copied into the columns below for that reason.
    slot_id      BIGINT      NOT NULL,
    -- The meal that was planned. The composite foreign key below requires it to belong to the same
    -- household, so the database refuses a cross-household link whatever the code does. No ON DELETE
    -- clause, as in V7 and V9: a meal that has ratings cannot be deleted (the app only archives).
    meal_id      BIGINT      NOT NULL,
    slot_date    DATE        NOT NULL,
    slot_type    VARCHAR(10) NOT NULL,
    user_id      BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    thumb        VARCHAR(4)  NOT NULL,
    stars        SMALLINT,
    -- Not called "comment": that is a reserved word on some databases.
    comment_text VARCHAR(500),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_rating_slot_type CHECK (slot_type IN ('BREAKFAST', 'LUNCH', 'DINNER', 'SNACK')),
    CONSTRAINT ck_rating_thumb CHECK (thumb IN ('UP', 'DOWN')),
    CONSTRAINT ck_rating_stars CHECK (stars BETWEEN 1 AND 5),
    CONSTRAINT fk_rating_meal FOREIGN KEY (meal_id, household_id)
        REFERENCES meal (id, household_id),
    -- One rating per member per slot. Giving again updates it; the unique key also makes two tabs
    -- racing each other end with one row.
    CONSTRAINT uq_rating_slot_user UNIQUE (slot_id, user_id)
);
-- A household's ratings by date: the "latest unrated slot" lookup and a slot's ratings.
CREATE INDEX ix_rating_household_date ON rating (household_id, slot_date);
-- The meal side of the foreign key, and a meal's rating history.
CREATE INDEX ix_rating_meal ON rating (meal_id);
-- The author side: deleting a user cascades to their ratings.
CREATE INDEX ix_rating_user ON rating (user_id);
