-- Identity (#12): users, the allowlist and the Spring Session JDBC tables. Portable SQL: it runs
-- unchanged on H2 (PostgreSQL mode) and on Postgres.

-- One row per person who has signed in. Rows are only created for allowlisted Google accounts.
CREATE TABLE app_user (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Google's stable account id (the OIDC "sub"). The e-mail can change; this cannot.
    google_sub   VARCHAR(255) NOT NULL,
    email        VARCHAR(320) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    -- UI language, hu or en (PLAN.md D14).
    locale       VARCHAR(8)   NOT NULL DEFAULT 'hu',
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_app_user_google_sub UNIQUE (google_sub)
);
CREATE INDEX ix_app_user_email ON app_user (email);

-- Who may sign in at all (PLAN.md D6). Addresses are stored lower-case. The bootstrap admins from
-- MM_ADMIN_EMAILS are allowed without a row here.
CREATE TABLE allowed_email (
    email      VARCHAR(320) PRIMARY KEY,
    -- ADMIN: added on the admin page. INVITE: added by a household invite (PLAN.md D9).
    source     VARCHAR(10)  NOT NULL,
    added_by   BIGINT REFERENCES app_user (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_allowed_email_source CHECK (source IN ('ADMIN', 'INVITE'))
);

-- Spring Session JDBC (PLAN.md D7): sessions live in the database so a redeploy, or the app waking
-- from sleep, does not sign anyone out. This is Spring Session's own PostgreSQL schema; H2 in
-- PostgreSQL mode accepts it as is.
CREATE TABLE spring_session (
    primary_id            CHAR(36)     NOT NULL,
    session_id            CHAR(36)     NOT NULL,
    creation_time         BIGINT       NOT NULL,
    last_access_time      BIGINT       NOT NULL,
    max_inactive_interval INT          NOT NULL,
    expiry_time           BIGINT       NOT NULL,
    principal_name        VARCHAR(100),
    CONSTRAINT spring_session_pk PRIMARY KEY (primary_id)
);
CREATE UNIQUE INDEX spring_session_ix1 ON spring_session (session_id);
CREATE INDEX spring_session_ix2 ON spring_session (expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session (principal_name);

CREATE TABLE spring_session_attributes (
    session_primary_id CHAR(36)     NOT NULL,
    attribute_name     VARCHAR(200) NOT NULL,
    attribute_bytes    BYTEA        NOT NULL,
    CONSTRAINT spring_session_attributes_pk PRIMARY KEY (session_primary_id, attribute_name),
    CONSTRAINT spring_session_attributes_fk FOREIGN KEY (session_primary_id)
        REFERENCES spring_session (primary_id) ON DELETE CASCADE
);
