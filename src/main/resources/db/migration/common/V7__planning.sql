-- Weekly plan (#80, PLAN.md Phase 3): one row per meal planned on a date, in one slot type.
-- The plan is stored per date; a week is a query over its seven dates (persistence.md).
-- Portable SQL: it runs unchanged on H2 (PostgreSQL mode) and on Postgres.

CREATE TABLE meal_slot (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT        NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    date         DATE          NOT NULL,
    slot_type    VARCHAR(10)   NOT NULL,
    -- Order inside (household, date, slot_type), counted from 0. The service keeps it contiguous
    -- (a remove or a move closes the gap). It is not unique on purpose: a reorder rewrites several
    -- rows, and a unique key would refuse the intermediate state. Ties sort by id.
    position     INT           NOT NULL,
    -- The planned meal. Not nullable: every slot holds a library meal. The composite foreign key
    -- requires the meal to belong to the same household, so the database refuses a cross-household
    -- link whatever the code does (as meal_tag does in V6). No ON DELETE clause: a meal that is still
    -- planned cannot be deleted, so no plan entry disappears silently. Archiving never deletes, so it
    -- never touches a slot (see PlanningService).
    meal_id      BIGINT        NOT NULL,
    note         VARCHAR(500),
    -- Optimistic locking: two people moving or editing the same slot get a conflict, not a lost edit.
    version      BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_meal_slot_type CHECK (slot_type IN ('BREAKFAST', 'LUNCH', 'DINNER', 'SNACK')),
    CONSTRAINT ck_meal_slot_position CHECK (position >= 0),
    CONSTRAINT fk_meal_slot_meal FOREIGN KEY (meal_id, household_id)
        REFERENCES meal (id, household_id)
);
-- The week view: the household's slots on seven consecutive dates.
CREATE INDEX ix_meal_slot_week ON meal_slot (household_id, date);
-- The meal side of the foreign key: checking that a planned meal may be deleted, and "where is this
-- meal planned?" (the library's recently-used list also reads the household index above).
CREATE INDEX ix_meal_slot_meal ON meal_slot (meal_id);
