-- Households (#41): the unit that owns all planning data (PLAN.md D8). Portable SQL: it runs
-- unchanged on H2 (PostgreSQL mode) and on Postgres.

CREATE TABLE household (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Optimistic locking: two members renaming at once get a conflict message, not a lost edit.
    version    BIGINT       NOT NULL DEFAULT 0
);

-- Who belongs to which household, and in which role. One person can be in many households.
CREATE TABLE membership (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT      NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    user_id      BIGINT      NOT NULL REFERENCES app_user (id),
    role         VARCHAR(10) NOT NULL,
    joined_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_membership_household_user UNIQUE (household_id, user_id),
    CONSTRAINT ck_membership_role CHECK (role IN ('OWNER', 'MEMBER'))
);
-- "Which households am I in?" runs on every request that shows the header.
CREATE INDEX ix_membership_user ON membership (user_id);
