-- Meal library (#66, PLAN.md Phase 2): the meals, the household's tags and which tags a meal has.
-- Portable SQL: it runs unchanged on H2 (PostgreSQL mode) and on Postgres.

-- A meal the household can plan and reuse. Archived meals stay in the table (their ratings and
-- past plans keep pointing at them) but leave the library's default list.
CREATE TABLE meal (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT        NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    name         VARCHAR(200)  NOT NULL,
    notes        VARCHAR(2000),
    recipe_url   VARCHAR(2000),
    archived     BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Optimistic locking: two people editing the same meal get a conflict, not a lost edit.
    version      BIGINT        NOT NULL DEFAULT 0,
    -- Target of the composite foreign key from meal_tag, so a tag link cannot cross households.
    CONSTRAINT uq_meal_id_household UNIQUE (id, household_id)
);
-- The library list starts from the household.
CREATE INDEX ix_meal_household ON meal (household_id);

-- A tag, per household. "Vegan" and "vegan" are the same tag: name_key is the lower-case name and
-- carries the uniqueness, while name keeps the spelling the household typed.
CREATE TABLE tag (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT       NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    name         VARCHAR(50)  NOT NULL,
    -- Wider than name: lower-casing can make a string longer (one capital dotted I becomes two
    -- characters).
    name_key     VARCHAR(100) NOT NULL,
    CONSTRAINT uq_tag_household_key UNIQUE (household_id, name_key),
    -- Target of the composite foreign key from meal_tag.
    CONSTRAINT uq_tag_id_household UNIQUE (id, household_id)
);

-- Which tags a meal has. household_id is stored too, and the two composite foreign keys require
-- both the meal and the tag to belong to that same household (persistence.md: join tables carry
-- the tenant).
CREATE TABLE meal_tag (
    meal_id      BIGINT NOT NULL,
    tag_id       BIGINT NOT NULL,
    household_id BIGINT NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    CONSTRAINT pk_meal_tag PRIMARY KEY (meal_id, tag_id),
    CONSTRAINT fk_meal_tag_meal FOREIGN KEY (meal_id, household_id)
        REFERENCES meal (id, household_id) ON DELETE CASCADE,
    CONSTRAINT fk_meal_tag_tag FOREIGN KEY (tag_id, household_id)
        REFERENCES tag (id, household_id) ON DELETE CASCADE
);
-- "Which meals have this tag?" (the tag filter) runs on the tag, not on the meal.
CREATE INDEX ix_meal_tag_tag ON meal_tag (tag_id);
-- The household's tag names for the library, and the tenant check on every join.
CREATE INDEX ix_meal_tag_household ON meal_tag (household_id);
