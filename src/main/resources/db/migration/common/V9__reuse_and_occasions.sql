-- Phase 4 (#109, PLAN.md D26): reusing days and weeks (plan templates) and planning dated occasions
-- (occasions and occasion templates), each with its items. Portable SQL: it runs unchanged on H2
-- (PostgreSQL mode) and on Postgres. Expand-only: new tables only, so the previous release keeps
-- working while this one rolls out (D13).
--
-- Every item table carries household_id with composite foreign keys to its parent and to meal, so
-- the database refuses a link across households whatever the code does (persistence.md). The meal
-- foreign keys have no ON DELETE clause on purpose, as in V7: a meal that a template or a menu
-- still uses cannot be deleted. The app only archives meals.

-- A saved day or week of the plan that can be applied again. Frozen: it can be renamed or deleted,
-- never edited, so its items need no version.
CREATE TABLE plan_template (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT       NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    name         VARCHAR(100) NOT NULL,
    scope        VARCHAR(4)   NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Optimistic locking: two people renaming or deleting the same template get a conflict.
    version      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_plan_template_scope CHECK (scope IN ('DAY', 'WEEK')),
    -- Target of the composite foreign key from plan_template_item.
    CONSTRAINT uq_plan_template_id_household UNIQUE (id, household_id)
);
CREATE INDEX ix_plan_template_household ON plan_template (household_id);

-- One meal in a plan template. day_offset counts from the first day: always 0 for a DAY template,
-- 0 (Monday) to 6 (Sunday) for a WEEK template.
CREATE TABLE plan_template_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id  BIGINT      NOT NULL,
    household_id BIGINT      NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    day_offset   INT         NOT NULL,
    slot_type    VARCHAR(10) NOT NULL,
    position     INT         NOT NULL,
    meal_id      BIGINT      NOT NULL,
    note         VARCHAR(500),
    CONSTRAINT ck_plan_template_item_offset CHECK (day_offset BETWEEN 0 AND 6),
    CONSTRAINT ck_plan_template_item_type CHECK (slot_type IN ('BREAKFAST', 'LUNCH', 'DINNER', 'SNACK')),
    CONSTRAINT ck_plan_template_item_position CHECK (position >= 0),
    CONSTRAINT fk_plan_template_item_template FOREIGN KEY (template_id, household_id)
        REFERENCES plan_template (id, household_id) ON DELETE CASCADE,
    CONSTRAINT fk_plan_template_item_meal FOREIGN KEY (meal_id, household_id)
        REFERENCES meal (id, household_id)
);
CREATE INDEX ix_plan_template_item_template ON plan_template_item (template_id);
CREATE INDEX ix_plan_template_item_meal ON plan_template_item (meal_id);
CREATE INDEX ix_plan_template_item_household ON plan_template_item (household_id);

-- A dated event with its own menu: a birthday, Christmas. The type reuses the catalog's
-- OccasionType (V8).
CREATE TABLE occasion (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id  BIGINT        NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    name          VARCHAR(100)  NOT NULL,
    date          DATE          NOT NULL,
    occasion_type VARCHAR(10)   NOT NULL,
    notes         VARCHAR(2000),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Optimistic locking: two people editing or deleting the same occasion get a conflict.
    version       BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_occasion_type CHECK (occasion_type IN ('BIRTHDAY', 'HOLIDAY', 'PARTY', 'OTHER')),
    -- Target of the composite foreign key from occasion_item.
    CONSTRAINT uq_occasion_id_household UNIQUE (id, household_id)
);
-- The week strip and the list: the household's occasions by date.
CREATE INDEX ix_occasion_household_date ON occasion (household_id, date);

-- One meal on an occasion's menu. No note and no version: adding only appends, and a removed or
-- moved item that is already gone is simply not found.
CREATE TABLE occasion_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occasion_id  BIGINT NOT NULL,
    household_id BIGINT NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    position     INT    NOT NULL,
    meal_id      BIGINT NOT NULL,
    CONSTRAINT ck_occasion_item_position CHECK (position >= 0),
    CONSTRAINT fk_occasion_item_occasion FOREIGN KEY (occasion_id, household_id)
        REFERENCES occasion (id, household_id) ON DELETE CASCADE,
    CONSTRAINT fk_occasion_item_meal FOREIGN KEY (meal_id, household_id)
        REFERENCES meal (id, household_id)
);
CREATE INDEX ix_occasion_item_occasion ON occasion_item (occasion_id);
CREATE INDEX ix_occasion_item_meal ON occasion_item (meal_id);
CREATE INDEX ix_occasion_item_household ON occasion_item (household_id);

-- A saved occasion menu that can start a new occasion on any date. It has no date of its own.
CREATE TABLE occasion_template (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id  BIGINT        NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    name          VARCHAR(100)  NOT NULL,
    occasion_type VARCHAR(10)   NOT NULL,
    notes         VARCHAR(2000),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Kept for a later rename; nothing bumps it in v1.
    version       BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_occasion_template_type CHECK (occasion_type IN ('BIRTHDAY', 'HOLIDAY', 'PARTY', 'OTHER')),
    -- Target of the composite foreign key from occasion_template_item.
    CONSTRAINT uq_occasion_template_id_household UNIQUE (id, household_id)
);
CREATE INDEX ix_occasion_template_household ON occasion_template (household_id);

-- One meal on an occasion template's menu.
CREATE TABLE occasion_template_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id  BIGINT NOT NULL,
    household_id BIGINT NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    position     INT    NOT NULL,
    meal_id      BIGINT NOT NULL,
    CONSTRAINT ck_occasion_template_item_position CHECK (position >= 0),
    CONSTRAINT fk_occasion_template_item_template FOREIGN KEY (template_id, household_id)
        REFERENCES occasion_template (id, household_id) ON DELETE CASCADE,
    CONSTRAINT fk_occasion_template_item_meal FOREIGN KEY (meal_id, household_id)
        REFERENCES meal (id, household_id)
);
CREATE INDEX ix_occasion_template_item_template ON occasion_template_item (template_id);
CREATE INDEX ix_occasion_template_item_meal ON occasion_template_item (meal_id);
CREATE INDEX ix_occasion_template_item_household ON occasion_template_item (household_id);
