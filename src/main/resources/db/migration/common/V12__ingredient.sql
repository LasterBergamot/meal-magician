-- Ingredients on meals (#155, PLAN.md D31): the household's ingredient names, which ingredients a
-- meal has, and a starter list of common Hungarian ingredients to suggest from. Names only, no
-- amounts. Portable SQL: it runs unchanged on H2 (PostgreSQL mode) and on Postgres.

-- An ingredient, per household. "Tojás", "tojas" and " TOJÁS " are the same ingredient: name_key is
-- the name with accents removed and in lower case, and carries the uniqueness, while name keeps the
-- spelling the household typed first.
CREATE TABLE ingredient (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT       NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    name         VARCHAR(60)  NOT NULL,
    -- Wider than name: folding and lower-casing can make a string longer in odd cases.
    name_key     VARCHAR(120) NOT NULL,
    CONSTRAINT uq_ingredient_household_key UNIQUE (household_id, name_key),
    -- Target of the composite foreign key from meal_ingredient.
    CONSTRAINT uq_ingredient_id_household UNIQUE (id, household_id)
);

-- Which ingredients a meal has. household_id is stored too, and the two composite foreign keys
-- require both the meal and the ingredient to belong to that same household (persistence.md: join
-- tables carry the tenant).
CREATE TABLE meal_ingredient (
    meal_id       BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    household_id  BIGINT NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    CONSTRAINT pk_meal_ingredient PRIMARY KEY (meal_id, ingredient_id),
    CONSTRAINT fk_meal_ingredient_meal FOREIGN KEY (meal_id, household_id)
        REFERENCES meal (id, household_id) ON DELETE CASCADE,
    CONSTRAINT fk_meal_ingredient_ingredient FOREIGN KEY (ingredient_id, household_id)
        REFERENCES ingredient (id, household_id) ON DELETE CASCADE
);
-- "Which meals have this ingredient?" (the ingredient filter) runs on the ingredient.
CREATE INDEX ix_meal_ingredient_ingredient ON meal_ingredient (ingredient_id);
-- The household's ingredient names for the library, and the tenant check on every join.
CREATE INDEX ix_meal_ingredient_household ON meal_ingredient (household_id);

-- The starter list the ingredient picker suggests from. Global, read-only reference data: the only
-- table without household_id, because nothing in it belongs to a household. A suggestion that is
-- picked becomes a normal ingredient row of the household.
CREATE TABLE ingredient_seed (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(60)  NOT NULL,
    -- The accent-folded, lower-case name, written out literally below; a test recomputes every key
    -- with MealRules.ingredientKey so a wrong one fails the build.
    name_key VARCHAR(120) NOT NULL UNIQUE
);

