-- Read-only share links to one ISO week (#125, PLAN.md D28). Portable SQL: it runs unchanged on H2
-- (PostgreSQL mode) and on Postgres.

CREATE TABLE share_link (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT      NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    -- SHA-256 of the token as hex. The token itself is never stored: whoever reads this table cannot
    -- build a working link from it.
    token_hash   VARCHAR(64) NOT NULL,
    -- The Monday of the shared ISO week. The service normalises any date to its Monday.
    week_start   DATE        NOT NULL,
    -- Kept for the household's own list; a person who leaves the app does not delete the link.
    created_by   BIGINT      REFERENCES app_user (id) ON DELETE SET NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at   TIMESTAMP WITH TIME ZONE,
    -- There is deliberately no "version" column (every change is a guarded UPDATE) and no
    -- "last_viewed_at": the public read path must stay write-free (D28).
    CONSTRAINT uq_share_link_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_share_link_expiry CHECK (expires_at > created_at)
);
-- The management list of one week, and the household's active-link count.
CREATE INDEX ix_share_link_household_week ON share_link (household_id, week_start);
