-- The assistant's drafts (#159, PLAN.md D32): a proposed week of meals that a member can refine,
-- trim and accept. Portable SQL: it runs unchanged on H2 (PostgreSQL mode) and on Postgres.
-- Expand-only: new tables, so the previous release keeps working while this one rolls out (D13).
--
-- A draft is short-lived. It is purged seven days after it was created, when the next draft is
-- made (no scheduler; see DraftService). It keeps the member's request text and the conversation
-- with the model until then, so both appear in backups.

CREATE TABLE assistant_draft (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT        NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    -- The app_user who asked. Deliberately no foreign key: it is only a record of who asked, and a
    -- member leaving or being deleted must not be blocked by (or silently delete) a draft.
    created_by   BIGINT        NOT NULL,
    -- The Monday of the ISO week the draft is for.
    week_start   DATE          NOT NULL,
    status       VARCHAR(10)   NOT NULL,
    -- What the member typed (at most 1 000 characters) plus up to four quick-request phrases the
    -- controller appends (#160 amendment), so up to 1 200.
    request_text VARCHAR(1200) NOT NULL,
    -- The turns so far as a JSON array of {role, text}, for follow-up requests.
    conversation TEXT          NOT NULL,
    summary      VARCHAR(1000),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Optimistic locking: a refine and an accept at the same moment cannot both win.
    version      BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_assistant_draft_status CHECK (status IN ('OPEN', 'ACCEPTED')),
    -- Target of the composite foreign key from assistant_draft_item.
    CONSTRAINT uq_assistant_draft_id_household UNIQUE (id, household_id)
);
CREATE INDEX ix_assistant_draft_household ON assistant_draft (household_id);
-- The purge: drafts older than a cutoff.
CREATE INDEX ix_assistant_draft_created ON assistant_draft (created_at);

-- One proposed meal in a draft: either a library meal (meal_id) or an "idea" (idea_*) that is not
-- in the library yet. Exactly one of the two is set; adding an idea to the library clears the idea
-- columns and sets meal_id.
CREATE TABLE assistant_draft_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id         BIGINT       NOT NULL,
    household_id     BIGINT       NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    day_date         DATE         NOT NULL,
    slot_type        VARCHAR(10)  NOT NULL,
    position         INT          NOT NULL,
    meal_id          BIGINT,
    idea_name        VARCHAR(100),
    idea_reason      VARCHAR(300),
    -- Names separated by a line feed (a name never contains one: the app collapses whitespace).
    idea_tags        VARCHAR(300),
    idea_ingredients VARCHAR(500),
    CONSTRAINT ck_assistant_draft_item_type CHECK (slot_type IN ('BREAKFAST', 'LUNCH', 'DINNER', 'SNACK')),
    CONSTRAINT ck_assistant_draft_item_position CHECK (position >= 0),
    CONSTRAINT ck_assistant_draft_item_kind CHECK (
        (meal_id IS NOT NULL AND idea_name IS NULL) OR (meal_id IS NULL AND idea_name IS NOT NULL)),
    CONSTRAINT fk_assistant_draft_item_draft FOREIGN KEY (draft_id, household_id)
        REFERENCES assistant_draft (id, household_id) ON DELETE CASCADE,
    -- A meal that is set must exist in the same household. With meal_id NULL (an idea) the
    -- constraint is not checked, which is what we want. No ON DELETE, as in V9: the app archives
    -- meals, it never deletes them.
    CONSTRAINT fk_assistant_draft_item_meal FOREIGN KEY (meal_id, household_id)
        REFERENCES meal (id, household_id)
);
CREATE INDEX ix_assistant_draft_item_draft ON assistant_draft_item (draft_id);
CREATE INDEX ix_assistant_draft_item_meal ON assistant_draft_item (meal_id);
CREATE INDEX ix_assistant_draft_item_household ON assistant_draft_item (household_id);
