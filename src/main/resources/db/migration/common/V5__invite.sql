-- Email-bound household invites (#42, PLAN.md D9). Portable SQL: it runs unchanged on H2
-- (PostgreSQL mode) and on Postgres.

CREATE TABLE invite (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT       NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    -- The address the invite is for, lower-case; joining needs the signed-in Google e-mail to match.
    email        VARCHAR(254) NOT NULL,
    -- SHA-256 of the code as hex. The code itself is never stored: whoever reads this table cannot
    -- build a working link from it.
    code_hash    VARCHAR(64)  NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at   TIMESTAMP WITH TIME ZONE,
    used_at      TIMESTAMP WITH TIME ZONE,
    used_by      BIGINT REFERENCES app_user (id),
    created_by   BIGINT       NOT NULL REFERENCES app_user (id),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_invite_code_hash UNIQUE (code_hash)
);
-- The owner's invite list.
CREATE INDEX ix_invite_household ON invite (household_id);
